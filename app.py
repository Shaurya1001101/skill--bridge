# ─── 2. Google Gemini Studio Client ───────────────────────────────────────────
def call_gemini(prompt: str, system_instruction: str = "") -> str:
    """Invokes Google Gemini Studio API (gemini-flash-latest)."""
    # 1. Primary: Direct high-speed REST endpoint
    try:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent?key={GEMINI_API_KEY}"
        payload = {
            "contents": [{"role": "user", "parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.4, "maxOutputTokens": 1200}
        }
        if system_instruction:
            payload["systemInstruction"] = {"parts": [{"text": system_instruction}]}
        
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}
        )
        with urllib.request.urlopen(req, timeout=25) as res:
            res_data = json.loads(res.read().decode("utf-8"))
            return res_data["candidates"][0]["content"]["parts"][0]["text"]
    except Exception as rest_err:
        pass

    # 2. Fallback: Google GenAI Python SDK
    try:
        from google import genai
        client = genai.Client(api_key=GEMINI_API_KEY)
        full_prompt = prompt
        if system_instruction:
            full_prompt = f"System Instruction:\n{system_instruction}\n\nUser Prompt:\n{prompt}"
            
        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=full_prompt
        )
        if response and response.text:
            return response.text
    except Exception as sdk_err:
        return f"Error connecting to Gemini Studio: {sdk_err}"
            
    return "No response generated by Gemini."

