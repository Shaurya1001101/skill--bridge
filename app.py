# ─── 4. Standalone HTTP Server for Local Web Integration ───────────────────────
class SkillBridgeHandler(BaseHTTPRequestHandler):
    def _send_json(self, status: int, data: dict):
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()
        self.wfile.write(json.dumps(data).encode("utf-8"))

    def do_OPTIONS(self):
        self.send_response(200)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

    def do_POST(self):
        content_length = int(self.headers.get("Content-Length", 0))
        post_data = self.rfile.read(content_length)
        body = json.loads(post_data.decode("utf-8")) if post_data else {}
        
        path = self.path.split("?")[0]
        
        if path == "/api/ai" or path == "/api/chat":
            msg = body.get("message", "")
            ctx = body.get("context", {})
            reply = chat_career_coach(msg, ctx)
            return self._send_json(200, {"reply": reply, "source": "gemini-flash-latest"})
            
        elif path == "/api/recommend/jobs":
            skills = body.get("skills", [])
            city = body.get("city", "")
            results = recommend_jobs(skills, city=city, limit=body.get("limit", 10))
            return self._send_json(200, {"jobs": results, "count": len(results)})
            
        elif path == "/api/analyze/gap":
            role = body.get("target_role", "Machine Learning Engineer")
            skills = body.get("skills", [])
            gap = analyze_skill_gap(role, skills)
            return self._send_json(200, gap)
            
        elif path == "/api/recommend/courses":
            skills = body.get("skills", [])
            courses = recommend_courses(skills)
            return self._send_json(200, {"courses": courses})
            
        self._send_json(404, {"error": "Not Found"})

    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        params = urllib.parse.parse_qs(parsed.query)
        
        if parsed.path == "/api/health":
            return self._send_json(200, {
                "status": "online",
                "model": "gemini-flash-latest",
                "datasets_loaded": True,
                "jobs_count": len(dataset_jobs)
            })
            
        elif parsed.path == "/api/insights":
            role = params.get("role", ["Data Scientist"])[0]
            role_benchmarks = trained_model.get("ds_stats", {}).get("role_benchmarks", {})
            return self._send_json(200, {
                "benchmarks": role_benchmarks,
                "total_jobs": len(dataset_jobs)
            })
            
        self._send_json(404, {"error": "Not Found"})

def run_server(port: int = 5050):
    server = HTTPServer(("0.0.0.0", port), SkillBridgeHandler)
    print(f"🚀 SkillBridge Gemini Python Server listening on http://localhost:{port}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nShutting down server.")
        server.server_close()

