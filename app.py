def recommend_jobs(user_skills: list, city: str = "", max_years: int = None, limit: int = 5):
    """Recommends matching tech postings from the real LinkedIn dataset."""
    u_skills_set = set(s.strip().lower() for s in user_skills if s)
    matches = []
    
    for job in dataset_jobs:
        j_skills = [s.strip().lower() for s in job.get("skills", [])]
        hits = [s for s in j_skills if s in u_skills_set]
        miss = [s for s in j_skills if s not in u_skills_set]
        
        pct = round((len(hits) / len(j_skills) * 100)) if j_skills else 0
        
        if city and city.lower() not in job.get("location", "").lower():
            continue
            
        if max_years is not None:
            min_y = job.get("min_years", 0)
            if min_y > max_years:
                continue
                
        matches.append({
            "title": job.get("title"),
            "company": job.get("company"),
            "location": job.get("location"),
            "match_percent": pct,
            "you_have": [s.title() for s in hits],
            "you_miss": [s.title() for s in miss],
            "apply_link": job.get("apply_link", "https://linkedin.com"),
            "skills": job.get("skills", [])
        })
        
    matches.sort(key=lambda x: x["match_percent"], reverse=True)
    return matches[:limit]

def analyze_skill_gap(target_role: str, user_skills: list):
    """Evaluates candidate against role competencies and returns prioritized gaps."""
    role_key = target_role.lower().replace(" ", "-")
    comp_map = trained_model.get("synthesis", {}).get("role_competencies", {})
    
    matched_role = None
    for k, v in comp_map.items():
        if k in role_key or role_key in k:
            matched_role = v
            break
            
    if not matched_role:
        core_skills = ["Python", "SQL", "Machine Learning", "Docker", "PyTorch", "MLOps"]
        salary_range = "14-35 LPA"
    else:
        core_skills = matched_role.get("core_skills", [])
        salary_range = matched_role.get("salary_range", "12-30 LPA")
        
    user_skills_lower = [s.strip().lower() for s in user_skills]
    have = [s for s in core_skills if s.lower() in user_skills_lower]
    missing = [s for s in core_skills if s.lower() not in user_skills_lower]
    readiness = round((len(have) / len(core_skills)) * 100) if core_skills else 0
    
    courses = [COURSE_CATALOG.get(m, {"title": f"{m} Masterclass", "platform": "Official Docs", "url": "https://google.com"}) for m in missing]
    
    return {
        "target_role": target_role,
        "readiness_percent": readiness,
        "salary_range_lpa": salary_range,
        "skills_possessed": have,
        "priority_gaps": missing,
        "recommended_courses": courses
    }

